const config = { scenarioId: 'main-street', seed: 'first-season' };
const opening: Command[] = [{ type: 'accept', requestId: 'd0-r0', maker: 'h1' }, { type: 'runDay' }, { type: 'runDay' }];
const returning: Command[] = [...opening, { type: 'choose', newsId: 'n2', option: 0 }, ...['d2-r0', 'd2-r1', 'd2-r4', 'd2-r5'].map(requestId => ({ type: 'accept' as const, requestId })), { type: 'runDay' }];
const saved = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('lantern.runs.v1')!)[0].commands as Command[]);

async function load(page: Page, commands: Command[], runConfig: RunConfig = config) {
  expect(replay(runConfig, commands).errors).toEqual([]);
  await page.goto('/');
  await page.evaluate(save => { localStorage.clear(); localStorage.setItem('lantern.guide.v1', 'seen'); localStorage.setItem('lantern.stamps.v1', JSON.stringify(['first-season'])); localStorage.setItem('lantern.runs.v1', JSON.stringify([save])); }, { v: 1, rules: RULES.version, id: 'commissions', label: 'Commissions', savedAt: new Date().toISOString(), config: runConfig, commands });
  await page.reload();
  await page.getByRole('button', { name: 'Continue Commissions', exact: true }).click();
}

