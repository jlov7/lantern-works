test('a regular can review a future studio slot and reserve it with exact native terms', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 844 });
  const before = replay(config, returning).state;
  expect(reservationBlocked(before, 'd3-r6', 1)).toBeNull();
  await load(page, returning);
  const ticket = await selectCustomer(page, 'd3-r6');
  await ticket.locator('.studio-slot > summary').click();
  await expect(ticket.locator('.studio-slot')).toContainText('It does not reserve Ada, Tomas or any other named maker');
  await ticket.getByRole('radio', { name: /in two days/ }).check();
  expect(await saved(page)).toEqual(returning);
  await ticket.getByRole('radio', { name: /tomorrow/ }).check();
  const request = before.requests.find(request => request.id === 'd3-r6')!;
  const reaction = reactionTo(before, request);
  if (reaction.kind !== 'buy') throw new Error('The returning customer must buy the fixture offer.');
  const proof = ordinaryBrief(request, reaction.offer);
  const command: Command = { type: 'reserve', requestId: 'd3-r6', startsInDays: 1, ...(proof ? { design: proof.defaultDesign } : {}) };
  const accepted = applyCommand(before, command);
  const contract = accepted.state.contracts.at(-1)!;
  await expect(ticket.locator('.studio-slot')).toContainText(`${credits(contract.price)} paid now`);
  const reserve = ticket.getByRole('button', { name: /^Reserve studio capacity/ });
  await reserve.focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('.reply-receipt')).toBeFocused();
  expect(await saved(page)).toEqual([...returning, command]);
  const actual = replay(config, await saved(page)).state;
  expect(actual).toEqual(accepted.state);
  expect(actual.jobs.filter(job => job.contractId === contract.id).every(job => job.maker === undefined && job.releaseDay === before.day + 1)).toBe(true);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.locator('[data-customer-heading]')).toBeFocused();
  expect(await saved(page)).toEqual(returning);
});

