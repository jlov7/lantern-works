import AxeBuilder from '@axe-core/playwright';
import { expect, test, type Locator, type Page } from '@playwright/test';
import { replay } from '../src/engine/sim';
import type { Command, RunConfig } from '../src/engine/types';
import { goPlace, takeFocused } from './workspace-helpers';

const saved = (page: Page): Promise<{ rules: string; config: RunConfig; commands: Command[] }> => page.evaluate(() => JSON.parse(localStorage.getItem('lantern.runs.v1')!)[0]);
const line = 'Stay for the last note';
const print = (svg: Locator) => svg.evaluate(element => ({
  layout: element.getAttribute('data-layout'), palette: element.getAttribute('data-palette'),
  typeface: element.getAttribute('data-typeface'), treatment: element.getAttribute('data-treatment'),
  label: element.getAttribute('aria-label'), text: element.textContent,
  illustrations: element.querySelector('.designed-artwork__illustrations')!.innerHTML,
}));

test('inspect the exact first proof before approval, with zoom and keyboard return', async ({ page }, info) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'First season: Main Street (guided)', exact: true }).click();
  const first = page.locator('.first-proof');
  await first.getByRole('button', { name: 'Put the musicians first', exact: true }).click();
  await first.getByRole('button', { name: 'River green', exact: true }).click();
  await first.locator('summary').click();
  await first.getByRole('textbox').fill(line);
  await page.evaluate(() => document.fonts.ready);
  const artwork = await print(first.locator('.first-proof__paper svg[data-layout]'));
  const tape = (await saved(page)).commands;
  const inspect = first.getByRole('button', { name: 'Inspect working proof', exact: true });
  await inspect.click();
  const dialog = page.getByRole('dialog', { name: 'Your working proof', exact: true });
  const viewport = dialog.getByRole('region', { name: 'Working proof', exact: true });
  const svg = viewport.locator('svg[data-layout]');
  await expect(dialog.getByRole('heading')).toBeFocused();
  await page.keyboard.press('Space');
  expect((await saved(page)).commands).toEqual(tape);
  expect(await print(svg)).toEqual(artwork);
  const fit = await svg.boundingBox();
  const area = await viewport.boundingBox();
  expect(fit!.width).toBeGreaterThan(280);
  expect(fit!.x).toBeGreaterThanOrEqual(area!.x);
  expect(fit!.y + fit!.height).toBeLessThanOrEqual(area!.y + area!.height);
  await dialog.screenshot({ path: info.outputPath('working-proof-fit.png') });
  expect((await new AxeBuilder({ page }).include('dialog[open]').analyze()).violations).toEqual([]);
  await dialog.getByRole('button', { name: 'Zoom in', exact: true }).click();
  const enlarged = await svg.boundingBox();
  expect(enlarged!.width).toBeGreaterThanOrEqual(fit!.width * 2);
  const detailPixels = await svg.locator(':scope > text').last().evaluate(element => Number(element.getAttribute('font-size')) * element.closest('svg')!.getBoundingClientRect().width / 100);
  expect(detailPixels).toBeGreaterThanOrEqual(14);
  await viewport.focus();
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('ArrowDown');
  await expect.poll(() => viewport.evaluate(element => element.scrollLeft)).toBeGreaterThan(0);
  await expect.poll(() => viewport.evaluate(element => element.scrollTop)).toBeGreaterThan(0);
  await dialog.screenshot({ path: info.outputPath('working-proof-zoom.png') });
  await dialog.getByRole('button', { name: 'Fit print', exact: true }).click();
  expect(await print(svg)).toEqual(artwork);
  await expect.poll(() => viewport.evaluate(element => element.scrollLeft)).toBe(0);
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(inspect).toBeFocused();
  await expect(first.getByRole('textbox')).toHaveValue(line);
  expect((await saved(page)).commands).toEqual(tape);
  await page.keyboard.press('Enter');
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Zoom in', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(inspect).toBeFocused();
  await page.getByRole('complementary', { name: 'Guide, step 1 of 5', exact: true }).getByRole('button', { name: 'Next', exact: true }).click();
  await takeFocused(page);
  const accepted = await saved(page);
  expect(accepted.commands.slice(0, -1)).toEqual(tape);
  expect(accepted.commands.at(-1)).toMatchObject({ type: 'accept', intention: 'clem-band', design: { pieces: [{ palette: 'river', headline: line }] } });
  expect(replay(accepted.config, accepted.commands, accepted.rules).errors).toEqual([]);
  const acceptedPrint = page.locator('.atelier-artwork svg[data-layout]');
  await expect(acceptedPrint).toHaveAttribute('aria-hidden', 'true');
  expect(await print(acceptedPrint)).toEqual({ ...artwork, label: null });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('a first creative promise survives Undo and reload, then becomes a remembered invitation', async ({ page }, info) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'First season: Main Street (guided)', exact: true }).click();
  const first = page.locator('.first-proof');
  await expect(first).toBeVisible();
  const before = await saved(page);
  await first.getByRole('button', { name: 'Put the musicians first', exact: true }).click();
  await first.getByRole('button', { name: 'River green', exact: true }).click();
  await first.locator('summary').click();
  await first.getByRole('textbox').fill(line);
  await expect(first.locator('svg[data-layout]')).toHaveAttribute('data-layout', 'headline');
  expect((await saved(page)).commands).toEqual(before.commands);
  await goPlace(page, 'Studio');
  await goPlace(page, 'Window');
  await expect(first.getByRole('textbox')).toHaveValue(line);
  await expect(first.getByRole('button', { name: 'Put the musicians first', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(first.locator('svg[data-palette]')).toHaveAttribute('data-palette', 'river');
  await page.evaluate(() => document.fonts.ready);
  await first.screenshot({ path: info.outputPath('first-proof.png') });
  expect((await new AxeBuilder({ page }).include('.first-proof').analyze()).violations).toEqual([]);
  await page.getByRole('complementary', { name: 'Guide, step 1 of 5', exact: true }).getByRole('button', { name: 'Next', exact: true }).click();
  await takeFocused(page);
  const accepted = await saved(page);
  expect(accepted.commands.at(-1)).toMatchObject({ type: 'accept', intention: 'clem-band', design: { pieces: [{ palette: 'river', headline: line }] } });
  const native = replay(accepted.config, accepted.commands, accepted.rules);
  expect(native.errors).toEqual([]);
  const approved = native.state.contracts[0]!.proof!;
  await expect(page.locator('.atelier-artwork svg[data-palette]')).toHaveAttribute('data-palette', 'river');
  await page.getByRole('button', { name: 'Undo reply', exact: true }).click();
  await expect(first.getByRole('textbox')).toHaveValue(line);
  await takeFocused(page);
  expect((await saved(page)).commands).toEqual(accepted.commands);
  await page.reload();
  await page.getByRole('button', { name: 'Continue the season', exact: true }).click();
  await page.getByRole('button', { name: /^Compare \/ All neighbours/ }).click();
  await page.getByRole('dialog', { name: 'Compare all neighbours' }).locator(`[data-request-id="${native.state.contracts[0]!.requestId}"]`).click();
  await expect(page.getByRole('region', { name: 'Customer reply' })).toContainText('Clem has your answer');
  await expect(page.locator('.atelier-artwork svg[data-palette]')).toHaveAttribute('data-palette', 'river');
  await page.getByRole('button', { name: /Open the shop for Day 1/ }).click();
  const delivered = page.locator('[data-payoff-kind="ordinary"]');
  await expect(delivered).toBeVisible();
  await expect(page.locator('.topbar-day')).toContainText('Day 1');
  await expect(page.locator('.topbar-day')).toContainText('evening');
  await expect(page.getByRole('button', { name: /Open the shop for Day 2/ })).toHaveCount(0);
  await expect(page.getByRole('button', { name: "Review tomorrow's window", exact: true })).toBeVisible();
  const beforeTomorrow = (await saved(page)).commands;
  await page.locator('#evening-h').focus();
  await page.keyboard.press('Space');
  expect((await saved(page)).commands).toEqual(beforeTomorrow);
  await expect(delivered).toContainText(line);
  await expect(delivered.locator('svg[data-palette]')).toHaveAttribute('data-palette', 'river');
  await page.screenshot({ path: info.outputPath('first-evening-viewport.png') });
  await delivered.screenshot({ path: info.outputPath('first-delivery.png') });
  const after = await saved(page);
  const reconstructed = replay(after.config, after.commands, after.rules);
  expect(reconstructed.errors).toEqual([]);
  expect(reconstructed.state.contracts[0]!.proof).toEqual(approved);
  expect(reconstructed.state.jobs[0]!.status).toBe('delivered');
  await delivered.getByRole('button', { name: 'See Clem Jazz Bar turns ten', exact: true }).click();
  await expect(page.locator('.commission-conversation')).toContainText('musicians');
  await page.locator('.commission-conversation__memory > summary').click();
  await expect(page.locator('.commission-conversation__memory svg[data-palette]')).toHaveAttribute('data-palette', 'river');
  await expect(page.locator('.commission-conversation__memory [role="img"]')).toHaveAccessibleName(new RegExp(line));
  await page.getByRole('button', { name: /The first-night photograph/ }).click();
  await expect(page.locator('.project-board')).toHaveClass(/project-board--editing/);
  await expect(page.locator('.proof-desk')).toHaveClass(/proof-desk--focused/);
  await expect(page.locator('.window-tools')).toHaveCount(0);
  await expect(page.getByRole('navigation', { name: 'Game places' })).toHaveCount(0);
  await expect(page.locator('.project-sketch-notice')).toContainText('Opens on Day 3');
  await expect(page.getByRole('region', { name: 'Day controls' }).getByRole('button', { name: /Keep sketch/ })).toBeVisible();
  const tape = (await saved(page)).commands;
  await page.locator('#project-quote-h').focus();
  await page.keyboard.press('Space');
  expect((await saved(page)).commands).toEqual(tape);
  await page.getByRole('button', { name: 'Keep sketch & return to customers', exact: true }).click();
  await page.getByRole('button', { name: /Open the shop for Day 2/ }).click();
  await expect(page.getByRole('button', { name: "Review tomorrow's window", exact: true })).toBeVisible();
  await page.getByRole('button', { name: "Review tomorrow's window", exact: true }).click();
  await page.locator('.project-notice').click();
  await expect(page.locator('.project-sketch-notice')).toHaveCount(0);
  const controls = page.getByRole('region', { name: 'Day controls' });
  await controls.getByRole('button', { name: 'Review proof & promise', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Approve the proof and the promise', exact: true })).toBeFocused();
  await controls.getByRole('button', { name: 'Book this proof', exact: true }).click();
  await expect(page.locator('.project-receipt')).toContainText('Booked: The first-night photograph');
  const booked = await saved(page);
  const final = replay(booked.config, booked.commands, booked.rules);
  expect(final.errors).toEqual([]);
  expect(final.state.contracts.find(contract => contract.project)?.project?.creativePromise?.design).toEqual(approved.design.pieces[0]);
  expect(final.state.contracts.find(contract => contract.project)?.project?.approach).toBe('first-night');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('the first proof remains usable at 320px and enlarged text', async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 844 });
  await page.goto('/');
  await page.getByRole('button', { name: 'First season: Main Street (guided)', exact: true }).click();
  await page.evaluate(() => document.documentElement.style.fontSize = '200%');
  const first = page.locator('.first-proof');
  await first.getByRole('button', { name: 'Give people a sense of the room', exact: true }).click();
  await first.getByRole('button', { name: 'Poppy & cream', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(first.locator('svg[data-palette]')).toHaveAttribute('data-palette', 'poppy');
  await first.locator('summary').click();
  await first.getByRole('textbox').fill('The room before the first set');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).include('.first-proof').analyze()).violations).toEqual([]);
  const tape = (await saved(page)).commands;
  const inspect = first.getByRole('button', { name: 'Inspect working proof', exact: true });
  await inspect.focus();
  await page.keyboard.press('Enter');
  const dialog = page.getByRole('dialog', { name: 'Your working proof', exact: true });
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeInViewport();
  await expect(dialog.getByRole('button', { name: 'Zoom in', exact: true })).toBeInViewport();
  await dialog.getByRole('button', { name: 'Zoom in', exact: true }).click();
  const viewport = dialog.getByRole('region', { name: 'Working proof', exact: true });
  await viewport.focus();
  await page.keyboard.press('ArrowDown');
  await expect.poll(() => viewport.evaluate(element => element.scrollTop)).toBeGreaterThan(0);
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeInViewport();
  await expect(dialog.getByRole('button', { name: 'Fit print', exact: true })).toBeInViewport();
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).include('dialog[open]').analyze()).violations).toEqual([]);
  await dialog.screenshot({ path: info.outputPath('working-proof-320-enlarged.png') });
  await page.keyboard.press('Escape');
  await expect(inspect).toBeFocused();
  await expect(first.getByRole('textbox')).toHaveValue('The room before the first set');
  expect((await saved(page)).commands).toEqual(tape);
});
